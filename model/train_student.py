#!/usr/bin/env python3
"""Distil YAMNet (teacher scores from teacher_label.py) into a small CNN and
export it as a C header for the firmware.

Student: conv3x3(1->C0)+pool, then depthwise-separable blocks, GAP, FC,
sigmoid outputs (multi-label). Per-class thresholds are chosen on the
validation clips for a maximum number of false events per hour (MAX_FALSE_PER_H).

Usage: .venv/bin/python train_student.py [--epochs N] [--width X] [--teachers panns_sed] [--tag NAME]
  --tag NAME: experiment, saves data/student_NAME.pt and does not touch the firmware header
"""
import argparse
import csv
import zlib
import time
import sys
from pathlib import Path

import numpy as np
import torch
import torch.nn as nn
import torch.nn.functional as F

sys.path.insert(0, str(Path(__file__).resolve().parent))
import features as fx  # noqa: E402
from features import ESC_GT  # noqa: E402

HERE = Path(__file__).resolve().parent
DATA = HERE / "data" / "teacher.npz"
OWN = HERE / "data" / "own.npz"
OUT_H = HERE.parent / "firmware" / "src" / "model_data.h"

C0 = 32
BLOCKS = [(64, True), (96, False), (128, False)]  # (out channels, maxpool after)
MAX_FALSE_PER_H = 10.0  # false events per hour of busy dataset audio, per class (home is mostly quiet)
N_CLASSES = len(fx.CLASS_NAMES)
DEV = "cuda" if torch.cuda.is_available() else "mps" if torch.backends.mps.is_available() else "cpu"


class DS(nn.Module):
    def __init__(self, cin, cout):
        super().__init__()
        self.dw = nn.Conv2d(cin, cin, 3, padding=1, groups=cin, bias=False)
        self.bdw = nn.BatchNorm2d(cin)
        self.pw = nn.Conv2d(cin, cout, 1, bias=False)
        self.bpw = nn.BatchNorm2d(cout)

    def forward(self, x):
        return F.relu(self.bpw(self.pw(F.relu(self.bdw(self.dw(x))))))


class Student(nn.Module):
    def __init__(self):
        super().__init__()
        self.c0 = nn.Conv2d(1, C0, 3, padding=1, bias=False)
        self.b0 = nn.BatchNorm2d(C0)
        blocks, cin = [], C0
        for cout, _ in BLOCKS:
            blocks.append(DS(cin, cout))
            cin = cout
        self.blocks = nn.ModuleList(blocks)
        self.drop = nn.Dropout(0.2)
        self.fc = nn.Linear(cin, N_CLASSES)

    def forward(self, x):
        x = F.max_pool2d(F.relu(self.b0(self.c0(x))), 2)
        for blk, (_, pool) in zip(self.blocks, BLOCKS):
            x = blk(x)
            if pool:
                x = F.max_pool2d(x, 2)
        return self.fc(self.drop(x.mean(dim=(2, 3))))


def fold(conv, bn):
    s = (bn.weight / torch.sqrt(bn.running_var + bn.eps)).detach()
    w = (conv.weight.detach() * s[:, None, None, None]).numpy().astype(np.float32)
    b = (bn.bias.detach() - bn.running_mean * s).numpy().astype(np.float32)
    return w, b


def c_array(name, arr):
    flat = np.asarray(arr, dtype=np.float32).ravel()
    body = ",\n".join("\t" + ", ".join(f"{v:.8e}f" for v in flat[i:i + 8])
                      for i in range(0, len(flat), 8))
    return f"static const float {name}[{len(flat)}] = {{\n{body}\n}};\n"


def header_common(norm_mean, norm_std, thresholds, confirm, note, guard):
    """Front end, classes and detection parameters shared by the float and int8 headers."""
    return [
        f"/* Generated by model/{Path(sys.argv[0]).name}, do not edit. */",
        f"/* {note} */",
        f"#ifndef {guard}\n#define {guard}\n",
        f"#define MD_SR {fx.SR}\n#define MD_N_FFT {fx.N_FFT}\n#define MD_WIN {fx.WIN}",
        f"#define MD_HOP {fx.HOP}\n#define MD_N_MELS {fx.N_MELS}\n#define MD_N_FRAMES {fx.N_FRAMES}",
        f"#define MD_LOG_EPS {fx.LOG_EPS}f",
        f"#define MD_NORM_MEAN {norm_mean:.8e}f\n#define MD_NORM_STD {norm_std:.8e}f",
        f"#define MD_N_CLASSES {N_CLASSES}\n#define MD_C0 {C0}\n#define MD_N_BLOCKS {len(BLOCKS)}\n",
        "static const char *const md_class_names[MD_N_CLASSES] = {"
        + ", ".join(f'"{c}"' for c in fx.CLASS_NAMES) + "};\n",
        c_array("md_thresholds", thresholds),
        "/* consecutive windows above threshold needed for an event */\n"
        f"static const unsigned char md_confirm[{N_CLASSES}] = {{{', '.join(str(int(k)) for k in confirm)}}};\n",
        c_array("md_mel_fb", fx.MEL_FB),
    ]


def export(net, norm_mean, norm_std, thresholds, confirm, note):
    net.eval()
    feat = fx.logmel(fx.test_signal())
    with torch.no_grad():
        logits = net(torch.from_numpy((feat - norm_mean) / norm_std)[None, None])[0].numpy()

    w0, b0 = fold(net.c0, net.b0)
    lines = header_common(norm_mean, norm_std, thresholds, confirm, note, "MODEL_DATA_H") + [
        c_array("md_c0_w", w0), c_array("md_c0_b", b0),
    ]
    descr = []
    cin = C0
    h, w = fx.N_FRAMES // 2, fx.N_MELS // 2
    max_act = max(fx.N_FRAMES * fx.N_MELS, C0 * h * w)
    for i, (blk, (cout, pool)) in enumerate(zip(net.blocks, BLOCKS)):
        dw_w, dw_b = fold(blk.dw, blk.bdw)
        pw_w, pw_b = fold(blk.pw, blk.bpw)
        lines += [c_array(f"md_b{i}_dw_w", dw_w), c_array(f"md_b{i}_dw_b", dw_b),
                  c_array(f"md_b{i}_pw_w", pw_w), c_array(f"md_b{i}_pw_b", pw_b)]
        descr.append(f"\t{{{cin}, {cout}, {int(pool)}, md_b{i}_dw_w, md_b{i}_dw_b, "
                     f"md_b{i}_pw_w, md_b{i}_pw_b}},")
        max_act = max(max_act, cin * h * w, cout * (h // 2) * (w // 2) if pool else cout * h * w)
        if pool:
            h, w = h // 2, w // 2
        cin = cout
    lines += [
        "struct md_block {\n\tint cin, cout, pool;\n\tconst float *dw_w, *dw_b, *pw_w, *pw_b;\n};\n",
        "static const struct md_block md_blocks[MD_N_BLOCKS] = {\n" + "\n".join(descr) + "\n};\n",
        f"#define MD_C_LAST {cin}",
        f"#define MD_MAX_ACT {max_act}",
        c_array("md_fc_w", net.fc.weight.detach().numpy()),
        c_array("md_fc_b", net.fc.bias.detach().numpy()),
        "/* Selftest: logits for the deterministic chirp (features.test_signal()) */",
        c_array("md_test_logits", logits),
        "#endif",
    ]
    OUT_H.write_text("\n".join(lines) + "\n")
    print(f"exported {OUT_H}, test logits {np.round(logits, 3)}")


# Dataset ground truth -> target class (combined with teacher scores)
GT_VALUE = 0.9
GT_LOUDEST_DB = 6.5  # only windows within this of the clip's loudest window


def apply_ground_truth(feat, target, group):
    """Raise targets for clip-level dataset labels on the clip's loud windows."""
    data = HERE / "data"
    clip_cls = {}
    for row in csv.DictReader(open(data / "esc50" / "ESC-50-master" / "meta" / "esc50.csv")):
        if row["category"] in ESC_GT:
            clip_cls[zlib.crc32(row["filename"].encode())] = {ESC_GT[row["category"]]}
    for path, cls in fx.fsd_clips():
        clip_cls[zlib.crc32(path.name.encode())] = cls

    energy = feat.mean(axis=(1, 2))
    order = np.argsort(group, kind="stable")
    g_sorted = group[order]
    starts = np.flatnonzero(np.r_[True, g_sorted[1:] != g_sorted[:-1]])
    ends = np.r_[starts[1:], len(order)]
    boosted = np.zeros(N_CLASSES, int)
    margin = GT_LOUDEST_DB / 10 * np.log(10)  # dB -> natural-log power units
    for s, e in zip(starts, ends):
        cls = clip_cls.get(int(g_sorted[s]))
        if not cls:
            continue
        idx = order[s:e]
        loud = idx[energy[idx] >= energy[idx].max() - margin]
        for name in cls:
            c = fx.CLASS_NAMES.index(name)
            target[loud, c] = np.maximum(target[loud, c], GT_VALUE)
            boosted[c] += len(loud)
    print("windows boosted by dataset labels:", dict(zip(fx.CLASS_NAMES, boosted.tolist())))


def predict(net, x, bs=1024):
    net.eval()
    out = []
    with torch.no_grad():
        for i in range(0, len(x), bs):
            out.append(torch.sigmoid(net(x[i:i + bs].to(DEV))).cpu().numpy())
    return np.concatenate(out)


def clip_bounds(group, exclude):
    """(start, end) of runs of equal group id with >= 3 windows (windows of a clip are contiguous)."""
    starts = np.flatnonzero(np.r_[True, group[1:] != group[:-1]])
    ends = np.r_[starts[1:], len(group)]
    keep = [(s, e) for s, e in zip(starts, ends) if e - s >= 3 and not exclude[s]]
    return np.array(keep, dtype=np.int64).reshape(-1, 2)


def pick_thresholds(prob, target, group, exclude):
    """Per class threshold and number of consecutive windows (1 or 2) like the device.

    Simulated on whole validation clips: recall = share of clips with the class
    (target > 0.5 in some window) that trigger at least once; false events =
    triggers in clips without the class (target < 0.2 everywhere) per hour of
    audio. Maximises recall with at most MAX_FALSE_PER_H false events.
    """
    bounds = clip_bounds(group, exclude)
    clip_id = np.full(len(group), -1)
    for i, (s, e) in enumerate(bounds):
        clip_id[s:e] = i
    inside = clip_id >= 0
    first = np.r_[True, clip_id[1:] != clip_id[:-1]]
    th = np.full(N_CLASSES, 0.95, np.float32)
    confirm = np.full(N_CLASSES, 2, np.int64)
    win_s = fx.SEG / 2 / fx.SR
    recalls = []
    for c in range(N_CLASSES):
        cmax = np.maximum.reduceat(target[:, c], bounds[:, 0]) if len(bounds) else np.zeros(0)
        pos_clip = cmax > 0.5
        neg_clip = cmax < 0.2
        neg_hours = np.sum((bounds[neg_clip, 1] - bounds[neg_clip, 0])) * win_s / 3600
        best = None
        for k in (2, 1):
            for t in np.linspace(0.2, 0.95, 31):
                above = (prob[:, c] >= t) & inside
                conf = above if k == 1 else above & np.r_[False, above[:-1]] & ~first
                start = conf & ~(np.r_[False, conf[:-1]] & ~first)
                trig = np.add.reduceat(start.astype(np.int64), bounds[:, 0])
                fph = trig[neg_clip].sum() / max(neg_hours, 1e-9)
                if fph > MAX_FALSE_PER_H:
                    continue
                rec = np.mean(trig[pos_clip] > 0) if pos_clip.any() else 0.0
                if best is None or rec > best[0] + 1e-9:
                    best = (rec, fph, t, k)
                break  # lowest passing threshold has the best recall for this k
        if best:
            rec, fph, th[c], confirm[c] = best
        else:
            rec, fph = float("nan"), float("nan")
        recalls.append(rec)
        print(f"  {fx.CLASS_NAMES[c]:12} thr {th[c]:.2f} windows {confirm[c]} clip recall {rec:.2f} "
              f"false {fph:.1f}/h ({pos_clip.sum()} clips, {neg_hours:.1f} h negative)")
    print(f"  mean clip recall {np.nanmean(recalls):.3f}")
    return th, confirm


# Extra teachers from teacher_torch.py (--teachers), combined with YAMNet by
# geometric mean on the real windows (clip-level AP vs dataset labels: YAMNet
# 0.674, PANNs SED 0.747, geometric mean 0.753). Off by default: on the device
# (10 clips per class) it gave 91/170 vs 94/170 for YAMNet alone.
EXTRA_TEACHERS = []
# Tonal alarm-like classes stay YAMNet only: PANNs scores them low, the geometric
# mean removed most positives (device test: beep 9/10 -> 0/10, phone_ring 5/10 -> 1/10)
YAMNET_ONLY = {"beep", "alarm", "smoke_alarm", "phone_ring"}


def combine_teachers(target, group):
    for name in EXTRA_TEACHERS:
        p = HERE / "data" / f"teacher_{name}.npz"
        if not p.exists():
            print(f"{p.name} missing, YAMNet targets only")
            continue
        d = np.load(p)
        w = d["window"]
        if not (group[w] == d["group"]).all():
            sys.exit(f"{p.name} does not match teacher.npz windows, relabel")
        cols = [c for c, cls in enumerate(fx.CLASS_NAMES) if cls not in YAMNET_ONLY]
        target[np.ix_(w, cols)] = np.sqrt(target[np.ix_(w, cols)] * d["target"][:, cols].astype(np.float32))
        print(f"combined {len(w)} windows with {name} (YAMNet only: {', '.join(sorted(YAMNET_ONLY))})")


def load_data():
    """All windows with targets, split and input normalisation (same for training and quantisation)."""
    d = np.load(DATA)
    feat = d["feat"]  # float16, converted per batch (all windows in float32 do not fit in RAM)
    target = d["target"].astype(np.float32)
    group = d["group"]
    combine_teachers(target, group)
    apply_ground_truth(feat, target, group)
    n_own = 0
    if OWN.exists():  # own recordings from own_label.py, labelled by hand
        o = np.load(OWN)
        n_own = len(o["feat"])
        feat = np.concatenate([feat, o["feat"].astype(np.float16)])
        target = np.concatenate([target, o["target"].astype(np.float32)])
        group = np.concatenate([group, o["group"]])
        print(f"added {len(o['feat'])} own windows from {OWN.name}")
    own = np.arange(len(group)) >= len(group) - n_own
    val = (group % 10) == 0
    tr = np.where(~val)[0]
    va = np.where(val)[0]
    sample = feat[np.random.default_rng(0).choice(tr, min(len(tr), 100000), replace=False)].astype(np.float64)
    norm_mean = float(sample.mean())
    norm_std = float(sample.std())
    print(f"windows train {len(tr)} val {len(va)}; positives (>0.5) per class:",
          dict(zip(fx.CLASS_NAMES, (target > 0.5).sum(0).tolist())))

    return dict(feat=feat, target=target, group=group, own=own, tr=tr, va=va,
                norm_mean=norm_mean, norm_std=norm_std)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--epochs", type=int, default=30)
    ap.add_argument("--export-only", action="store_true", help="reuse data/student.pt")
    ap.add_argument("--width", type=float, default=1.0, help="channel multiplier (experiments)")
    ap.add_argument("--teachers", nargs="*", default=[], help="extra teachers, e.g. panns_sed")
    ap.add_argument("--tag", help="experiment name: data/student_TAG.pt, no firmware export")
    a = ap.parse_args()
    global C0, BLOCKS
    C0 = int(round(C0 * a.width))
    BLOCKS = [(int(round(c * a.width)), p) for c, p in BLOCKS]
    EXTRA_TEACHERS[:] = a.teachers
    pt = HERE / "data" / (f"student_{a.tag}.pt" if a.tag else "student.pt")
    torch.manual_seed(0)
    rng = np.random.default_rng(0)

    D = load_data()
    feat, target, group, own, tr, va = (D[k] for k in ("feat", "target", "group", "own", "tr", "va"))
    norm_mean, norm_std = D["norm_mean"], D["norm_std"]

    # class-balanced sampling: 70 % of each batch are positives of a uniformly
    # chosen class (teacher > 0.5), 30 % random windows (mostly negatives)
    pos_idx = [tr[target[tr, c] > 0.5] for c in range(N_CLASSES)]

    def sample_batch(n):
        n_pos = int(n * 0.7)
        cls = rng.integers(0, N_CLASSES, n_pos)
        picks = [rng.choice(pos_idx[c]) for c in cls if len(pos_idx[c])]
        return np.concatenate([np.array(picks, dtype=np.int64), rng.choice(tr, n - len(picks))])

    net = Student().to(DEV)
    print("device", DEV)
    print("params", sum(p.numel() for p in net.parameters()))
    opt = torch.optim.AdamW(net.parameters(), lr=3e-3, weight_decay=1e-3)
    sched = torch.optim.lr_scheduler.OneCycleLR(opt, 3e-3, total_steps=a.epochs * 300)
    xv = torch.from_numpy((feat[va].astype(np.float32) - norm_mean) / norm_std)[:, None]
    truth = target[va] > 0.5

    if a.export_only:
        net.load_state_dict(torch.load(pt))
    for ep in range(0 if a.export_only else a.epochs):
        net.train()
        for _ in range(300):
            idx = sample_batch(128)
            x = feat[idx] + rng.uniform(-9.2, 2.3, (len(idx), 1, 1)).astype(np.float32)  # gain -40..+10 dB
            x = torch.from_numpy((x - norm_mean) / norm_std)[:, None].to(DEV)
            y = torch.from_numpy(target[idx]).to(DEV)
            # mixup with max of soft labels
            perm = torch.randperm(len(idx), device=DEV)
            lam = float(rng.beta(0.4, 0.4))
            mix = rng.random() < 0.3
            if mix:
                x = lam * x + (1 - lam) * x[perm]
                y = torch.maximum(y, y[perm])
            loss = F.binary_cross_entropy_with_logits(net(x), y)
            opt.zero_grad()
            loss.backward()
            opt.step()
            sched.step()
        prob = predict(net, xv)
        aps = []
        for c in range(N_CLASSES):
            if truth[:, c].sum() == 0:
                continue
            order = np.argsort(-prob[:, c])
            hits = truth[order, c]
            prec = np.cumsum(hits) / np.arange(1, len(hits) + 1)
            aps.append((prec * hits).sum() / hits.sum())
        print(f"{time.strftime('%H:%M:%S')} epoch {ep + 1:3d} loss {loss.item():.4f} val mAP(vs teacher) {np.mean(aps):.3f}", flush=True)

    prob = predict(net, xv)
    print(f"thresholds for <= {MAX_FALSE_PER_H} false events per hour (validation clips):")
    th, confirm = pick_thresholds(prob, target[va], group[va], own[va])
    own_va = own[va]
    for c in range(N_CLASSES):
        pos = own_va & (target[va, c] > 0.5)
        if pos.any():
            print(f"  own recordings {fx.CLASS_NAMES[c]}: recall {np.mean(prob[pos, c] >= th[c]):.2f} "
                  f"({pos.sum()} val windows, augmented copies of the same recordings)")
    net = net.cpu()
    torch.save(net.state_dict(), pt)
    if a.tag:
        return
    export(net, norm_mean, norm_std, th, confirm, f"distilled from YAMNet, {len(tr)} train windows")


if __name__ == "__main__":
    main()
